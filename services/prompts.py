def format_glossary_line(g: Dict[str, Any]) -> str:
    """Форматирует строку глоссария с учетом наличия японского оригинала."""
    jap = (g.get("jap_word") or "").strip()
    rus = (g.get("rus_word") or "").strip()
    ctx = (g.get("context") or "").strip()

    line = f"- {jap} -> {rus}" if jap else f"- Персонаж / Роль: {rus}"
    if ctx:
        line += f" ({ctx})"
    return line


def build_single_translate_prompt(text: str, title_description: str = "") -> str:
    synopsis_block = f"\nСтиль и синопсис тайтла:\n{title_description.strip()}\n" if title_description.strip() else ""
    return SINGLE_PROMPT_TEMPLATE.format(synopsis_block=synopsis_block, text=text.strip())


def build_page_batch_prompt(
    dialogue_text: str,
    title_description: str = "",
    glossary_rows: List[Dict[str, Any]] = None
) -> str:
    synopsis_block = ""
    if title_description and title_description.strip():
        synopsis_block = (
            "\nСИНОПСИС И СТИЛЬ ПОВЕСТВОВАНИЯ (СТРОГО СОБЛЮДАЙ ЭТОТ ТОН И ХАРАКТЕРЫ):\n"
            f"{title_description.strip()}\n"
        )

    glossary_block = ""
    if glossary_rows:
        glossary_lines = [format_glossary_line(g) for g in glossary_rows]
        glossary_block = (
            "\nОБЯЗАТЕЛЬНЫЙ ГЛОССАРИЙ И СПИСОК ПЕРСОНАЖЕЙ (СТРОГО используй эти имена и стили речи):\n"
            + "\n".join(glossary_lines)
            + "\n"
        )

    return PAGE_PROMPT_TEMPLATE.format(
        synopsis_block=synopsis_block,
        glossary_block=glossary_block,
        dialogue_text=dialogue_text.strip()
    )


def build_chapter_batch_prompt(
    full_text: str,
    title_description: str = "",
    glossary_rows: List[Dict[str, Any]] = None
) -> str:
    synopsis_prompt = ""
    if title_description and title_description.strip():
        synopsis_prompt = (
            "\nСИНОПСИС И СТИЛЬ ПОВЕСТВОВАНИЯ (СТРОГО СОБЛЮДАЙ ЭТОТ ТОН И ХАРАКТЕРЫ):\n"
            f"{title_description.strip()}\n"
        )

    glossary_prompt = ""
    if glossary_rows:
        glossary_lines = [format_glossary_line(g) for g in glossary_rows]
        glossary_prompt = (
            "\nОБЯЗАТЕЛЬНЫЙ ГЛОССАРИЙ И СПИСОК ПЕРСОНАЖЕЙ (СТРОГО используй эти имена и правила речи):\n"
            + "\n".join(glossary_lines)
            + "\n"
        )

    return CHAPTER_PROMPT_TEMPLATE.format(
        synopsis_block=synopsis_prompt,
        glossary_block=glossary_prompt,
        full_text=full_text.strip()
    )