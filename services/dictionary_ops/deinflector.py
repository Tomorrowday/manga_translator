# Ограничение на глубину и количество кандидатов, чтобы не раздувать поиск на длинных баблах
MAX_DEINFLECT_DEPTH = 3
MAX_DEINFLECT_CANDIDATES = 128


def kata_to_hira(text: str) -> str:
    """Конвертирует катакану в хирагану (диапазон Unicode 0x30A1..0x30F6 -> 0x3041..0x3096)."""
    if not text:
        return ""
    return "".join(
        chr(ord(ch) - 0x60) if "\u30a1" <= ch <= "\u30f6" else ch
        for ch in text
    )


def collapse_manga_emphasis(text: str) -> str:
    """Схлопывает экспрессивные повторы и удлинения манги: すっっっごい -> すごい, あああ -> あ."""
    if not text:
        return ""
    res = re.sub(r"っ{2,}", "っ", text)
    res = re.sub(r"ッ{2,}", "ッ", res)
    res = re.sub(r"ー{2,}", "ー", res)
    res = re.sub(r"(.)\1{2,}", r"\1", res)
    return res


def deinflect_candidates(surface: str) -> List[Tuple[str, List[str], List[str]]]:
    """
    Генерирует список кандидатов начальной формы:
    [(candidate_word, [reason_ru, ...], [required_rule_tags, ...]), ...]
    """
    if not surface:
        return []

    variants = [surface]
    collapsed = collapse_manga_emphasis(surface)
    if collapsed and collapsed not in variants:
        variants.append(collapsed)

    # Если слово содержит длинное тире в конце эмоции (например, すげー -> すげい / すごい)
    if collapsed.endswith("ー") and len(collapsed) >= 2:
        without_bar = collapsed[:-1]
        if without_bar not in variants:
            variants.append(without_bar)

    hira = kata_to_hira(collapsed)
    if hira and hira not in variants:
        variants.append(hira)

    results: List[Tuple[str, List[str], List[str]]] = []
    seen = set()
    queue = deque()

    for v in variants:
        if v and v not in seen:
            seen.add(v)
            results.append((v, [], []))
            queue.append((v, [], [], 0))

    while queue:
        word, reasons, req_rules, depth = queue.popleft()
        if depth >= MAX_DEINFLECT_DEPTH:
            continue

        for reason, kin, kout, _rin, rout in DEINFLECT_RULES:
            if not word.endswith(kin) or len(word) <= len(kin):
                continue
            stem = word[:-len(kin)] + kout
            if stem in seen:
                continue

            seen.add(stem)
            new_reasons = reasons + [reason]
            new_rules = list(dict.fromkeys(req_rules + list(rout)))
            results.append((stem, new_reasons, new_rules))
            queue.append((stem, new_reasons, new_rules, depth + 1))

            if len(results) >= MAX_DEINFLECT_CANDIDATES:
                return results

    return results
